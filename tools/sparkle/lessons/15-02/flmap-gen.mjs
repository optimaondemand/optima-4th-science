import fs from 'fs';
import * as topo from 'topojson-client';
import { geoConicConformal, geoPath, geoCentroid } from 'd3-geo';
const us = JSON.parse(fs.readFileSync('node_modules/us-atlas/counties-10m.json'));
const states = topo.feature(us, us.objects.states).features;
const fl = states.find(s => s.id === '12');
const W = 600, H = 560;
const proj = geoConicConformal().parallels([24.5, 31]).rotate([83.5, 0]).fitExtent([[12, 12], [W - 12, H - 12]], fl);
const path = geoPath(proj);
const r = s => s.replace(/(\d+\.\d)\d+/g, '$1');
const outline = r(path(fl));
const counties = us.objects.counties.geometries.filter(g => g.id.startsWith('12'));
const cmesh = r(path(topo.mesh(us, { type: 'GeometryCollection', geometries: counties }, (a, b) => a !== b)));
const coast = r(path(topo.mesh(us, us.objects.states, (a, b) => a === b && a.id === '12')));
const CIT = ['12105','12055','12027','12051','12049','12111','12061','12021','12085','12069'];
const cfeat = topo.feature(us, { type: 'GeometryCollection', geometries: counties.filter(g => CIT.includes(g.id)) });
const citrus = r(path(topo.merge(us, counties.filter(g => CIT.includes(g.id)))));
const citrusPts = cfeat.features.map(f => proj(geoCentroid(f)).map(v => +v.toFixed(1)));
const P = (lat, lon) => proj([lon, lat]).map(v => +v.toFixed(1));
const springs = [[30.235,-84.303],[30.790,-85.140],[30.481,-83.244],[30.006,-82.998],[30.084,-83.075],[29.984,-82.762],[29.836,-82.700],[29.826,-82.649],[29.587,-82.935],[29.489,-82.977],[29.102,-82.437],[29.216,-82.053],[29.246,-81.643],[29.081,-81.576],[28.947,-81.340],[28.712,-81.460],[28.517,-82.573],[28.715,-82.576],[28.799,-82.588],[28.894,-82.594],[30.425,-85.546]].map(a => P(...a));
const mines = [[27.66,-82.10],[27.53,-82.05],[27.62,-81.85],[27.73,-81.92],[27.85,-81.98],[27.45,-81.92],[27.73,-82.12],[27.88,-82.05],[27.57,-81.95],[30.40,-82.78],[30.47,-82.86]].map(a => P(...a));
const beaches = [[30.33,-87.14],[30.18,-85.80],[27.98,-82.83],[26.14,-81.80],[25.79,-80.13],[29.21,-81.01],[29.86,-81.27],[24.55,-81.80],[26.12,-80.10],[28.32,-80.61],[29.65,-84.95],[27.33,-82.58]].map(a => P(...a));
// coastline samples for distance
const cg = topo.mesh(us, us.objects.states, (a, b) => a === b && a.id === '12');
const coastPts = []; for (const line of cg.coordinates) for (let i = 0; i < line.length; i += 3) coastPts.push(proj(line[i]).map(v => +v.toFixed(0)));
const a = proj([-82, 27]), b = proj([-82, 28]);
const perMile = Math.hypot(a[0] - b[0], a[1] - b[1]) / 69.0;
const cities = { Tallahassee: P(30.44,-84.28), Jacksonville: P(30.33,-81.66), Orlando: P(28.54,-81.38), Tampa: P(27.95,-82.46), Miami: P(25.76,-80.19), Pensacola: P(30.42,-87.22), Gainesville: P(29.65,-82.32) };
const pins = { miami: P(25.80,-80.40), pensacola: P(30.33,-87.14), mulberry: P(27.86,-81.99), white: P(30.33,-82.76) };
const out = { viewBox: `0 0 ${W} ${H}`, outline, counties: cmesh, coast, citrus, perMile: +perMile.toFixed(4), springs, mines, beaches, citrusPts, coastPts, cities, pins };
fs.writeFileSync('flmap.json', JSON.stringify(out));
console.log('sizes', outline.length, cmesh.length, coast.length, citrus.length, coastPts.length, 'perMile', perMile, JSON.stringify(cities), JSON.stringify(pins));
